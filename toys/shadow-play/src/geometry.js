/**
 * 影人的皮件几何。所有坐标在骨骼局部空间：
 * 骨骼自 (0,0) 沿 +x 延伸到 (length, 0)。
 *
 * 朝上的骨骼（躯干、头）局部 +y 指向影人正面；
 * 朝下的骨骼（四肢）局部 -y 指向正面。见 puppet.js 的角度约定。
 *
 * @typedef {[number, number]} Pt
 * @typedef {{ outline: Pt[], holes: Pt[][], cuts: Pt[][] }} Piece
 *   outline 是轮廓，holes 是透光的镂空，cuts 是刻线（细的透光缝）。
 */

const TAU = Math.PI * 2;

/** @returns {Pt[]} */
export function circle(cx, cy, r, seg = 14) {
  const pts = [];
  for (let i = 0; i < seg; i++) {
    const a = (i / seg) * TAU;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return pts;
}

/** @returns {Pt[]} */
export function diamond(cx, cy, rx, ry) {
  return [
    [cx, cy - ry],
    [cx + rx, cy],
    [cx, cy + ry],
    [cx - rx, cy],
  ];
}

/**
 * 沿一条线均匀打一排孔。
 * @param {Pt} a @param {Pt} b @returns {Pt[][]}
 */
export function dotRow(a, b, n, r, kind = 'circle') {
  const out = [];
  for (let i = 0; i < n; i++) {
    const t = n === 1 ? 0.5 : i / (n - 1);
    const x = a[0] + (b[0] - a[0]) * t;
    const y = a[1] + (b[1] - a[1]) * t;
    out.push(kind === 'circle' ? circle(x, y, r, 10) : diamond(x, y, r, r * 1.5));
  }
  return out;
}

/**
 * 缠枝花：一个中心孔 + 一圈花瓣。皮影上最常见的装饰母题。
 * @returns {Pt[][]}
 */
export function rosette(cx, cy, r, petals = 6) {
  const out = [circle(cx, cy, r * 0.34, 10)];
  for (let i = 0; i < petals; i++) {
    const a = (i / petals) * TAU;
    out.push(diamond(cx + Math.cos(a) * r * 0.72, cy + Math.sin(a) * r * 0.72, r * 0.2, r * 0.34));
  }
  return out;
}

