// ——————————————————————————————————————————
// 配角的皮子。跟悟空同一套刻法：侧脸、缠枝镂空、刻线。
// Piece 多一个可选的 bones 字段：只在火眼金睛聚起来时才挖，
// 白骨就是从这些孔里透出来的。
// ——————————————————————————————————————————

/**
 * 凡人的侧脸。局部 +x = 脖子→头顶，+y = 脸朝的方向，跟悟空一致。
 *
 * 每个造型写成一条完整的闭合轮廓，不用 splice 往里插点 ——
 * 闭合的 Catmull-Rom 插点会让路径折回去，头顶就会冒出个钩子。
 * 多写几行换一个"改一个造型不会弄坏别的"的形状。
 *
 * @param {'girl'|'crone'|'oldman'|'monk'} kind
 * @returns {Piece}
 */
export function folkHead(kind) {
  /** 脸：额→眉→鼻→嘴→下巴。四个造型共用，下颌单独接。 */
  const face = [
    [80, 4],   // 额
    [76, 18],  // 眉骨
    [70, 26],  // 鼻梁
    [66, 34],  // 鼻尖 —— 凡人的鼻子不挑
    [60, 29],  // 人中
    [54, 33],  // 嘴
    [46, 38],  // 下巴
  ];

  /** @type {Pt[]} */
  let crown;
  /** @type {Pt[][]} */
  const holes = [diamond(70, 15, 5.2, 3.7)]; // 吊梢眼比圆眼更像皮影脸谱
  /** @type {Pt[][]} */
  const cuts = [
    [[76, 22], [69, 23], [62, 23]], // 眉
    [[68, 20], [64, 27], [60, 30]], // 鼻梁
    [[52, 31], [46, 30]], // 嘴
    [[44, 36], [32, 29], [18, 21]], // 下颌线
  ];

  if (kind === 'girl') {
    // 后脑挽一个发髻，把"年轻女子"一眼交出去
    crown = [
      [0, -14], [10, -28], [4, -40], [18, -46],
      [34, -40], [48, -34], [66, -26], [78, -12],
    ];
    holes.push(...rosette(18, -37, 9, 5), ...dotRow([36, -32], [61, -22], 4, 2.5, 'diamond'));
    cuts.push([[24, -32], [46, -28], [66, -18]]); // 发际
  } else if (kind === 'crone') {
    // 包头巾：顶上方一点，后面垂一条巾角
    crown = [
      [-4, -10], [-14, -26], [4, -42], [26, -50],
      [52, -46], [70, -32], [80, -14],
    ];
    holes.push(...dotRow([10, -34], [55, -34], 5, 2.5, 'diamond'));
    cuts.push([[70, -24], [44, -34], [12, -30]], [[-6, -22], [-10, -34]]);
  } else if (kind === 'oldman') {
    // 毡帽：平沿前后都出头，帽筒压得低
    crown = [
      [0, -14], [-2, -30], [16, -34], [14, -50],
      [46, -54], [62, -48], [64, -32], [82, -28], [82, -12],
    ];
    holes.push(...rosette(38, -43, 8, 5));
    cuts.push([[16, -32], [46, -36], [66, -28]]); // 帽沿
  } else {
    // 唐僧的毗卢帽：方、正、比头高一截。这顶帽子就是他的名牌。
    // 再高就成烟囱了
    crown = [
      [0, -12], [6, -26],
      [84, -30], [92, -33], [104, -29],
      [108, -14], [108, 6], [100, 14],
      [90, 17], [84, 12], [82, -2],
    ];
    holes.push(...dotRow([92, -16], [92, 6], 2, 3.4));
    cuts.push([[84, -20], [82, 10]]); // 帽檐，把帽和脸分开
  }

  // 白须要长在轮廓里。刻线画在皮子外面只会把黑线描到布幕上 ——
  // cuts 是 destination-out，皮子没盖到的地方没东西可挖。
  /** @type {Pt[]} */
  let jaw;
  if (kind === 'oldman') {
    // 须要往下垂 —— 局部 -x 才是"下"（+x 是脖子→头顶）。
    // 往 +y 伸就成了鸟嘴
    jaw = [[38, 42], [16, 44], [-2, 38], [-14, 26], [-6, 14], [8, 18]];
    cuts.push([[20, 38], [2, 32]], [[24, 26], [4, 22]]); // 须上的几道
  } else {
    jaw = [[32, 32], [14, 23]];
  }

  return {
    outline: [...crown, ...face, ...jaw],
    holes,
    cuts,
    // 骷髅：眼窝、鼻孔、牙缝。照着侧脸摆，挖开就是白骨的脸
    bones: [
      circle(66, 10, 10, 12),
      diamond(70, 27, 3.2, 5),
      ...dotRow([46, 33], [62, 28], 4, 2.4),
      circle(30, -6, 8, 10),
      ...dotRow([12, -14], [20, -26], 2, 3),
    ],
  };
}

/**
 * 凡人的躯干：下摆宽、腰收进去、肩再窄一点。
 * 收腰这一下很关键 —— 不收就是个灯罩。
 * bones 是肋骨和盆骨的镂孔，白骨精用得上。
 * @param {'girl'|'crone'|'oldman'|'monk'} kind
 * @returns {Piece}
 */
export function folkTorso(kind) {
  // 女相裙摆最阔，僧的袈裟次之，老者的袍收着。
  // 阔过 42 腿就被裙子吃掉了，走起来看不见步子
  const hem = kind === 'girl' ? 42 : kind === 'monk' ? 40 : 34;
  const waist = kind === 'oldman' ? 27 : 29;

  const outline = [
    // 背面：下摆 → 腰 → 肩
    [-4, -hem],
    [30, -hem + 4],
    [62, -waist - 4],
    [92, -waist],
    [118, -30],
    [136, -22],
    // 肩口，脖子从这儿出去
    [140, -6],
    [136, 12],
    // 正面：肩 → 胸 → 腰 → 下摆
    [118, 24],
    [92, waist],
    [62, waist + 6],
    [30, hem - 2],
    [-4, hem],
    // 下摆底边
    [-14, hem - 12],
    [-16, 0],
    [-14, -hem + 12],
  ];

  /** @type {Pt[][]} */
  const holes = [];
  // 刻线要顺着身子的长轴走（沿 +x），不能横着拦腰划 ——
  // 横线一多，人就像裹了绷带。悟空身上也是前襟、褶子这种竖线。
  /** @type {Pt[][]} */
  const cuts = [
    // 前襟：从领口一路开到下摆
    [[130, 14], [96, 22], [56, 30], [16, hem - 6]],
    // 领
    [[132, -6], [126, 12]],
  ];

  if (kind === 'monk') {
    // 袈裟的方格：一格一格挖，是他身上唯一的花
    for (let i = 0; i < 3; i++) {
      holes.push(...dotRow([46 + i * 30, -18], [46 + i * 30, 18], 2, 3.4));
    }
    // 袈裟的缝：两道竖的
    cuts.push([[120, -14], [80, -12], [40, -8]], [[116, 6], [76, 12], [34, 18]]);
  } else if (kind === 'girl') {
    holes.push(
      ...rosette(94, -2, 13, 7),
      ...rosette(54, 3, 10, 6),
      ...dotRow([20, -29], [20, 29], 5, 2.8, 'diamond'),
    );
    // 裙褶：三道竖线，走起来才有布的感觉
    cuts.push(
      [[56, -22], [30, -20], [8, -hem + 10]],
      [[52, 6], [26, 14], [4, hem - 10]],
    );
  } else if (kind === 'crone') {
    holes.push(...rosette(82, -1, 10, 5), ...dotRow([28, -24], [28, 24], 4, 2.6, 'diamond'));
    cuts.push([[110, -16], [70, -14], [26, -10]], [[60, 12], [30, 18], [6, hem - 8]]);
  } else {
    // 老者：袍身两道竖褶，别太花
    holes.push(...dotRow([82, -18], [82, 18], 3, 3, 'diamond'));
    cuts.push([[110, -16], [70, -14], [26, -10]], [[60, 12], [30, 18], [6, hem - 8]]);
  }

  return {
    outline,
    holes,
    cuts,
    // 白骨：三对肋 + 盆骨。只在看破时才挖开
    bones: [
      ...ribPair(62), ...ribPair(88), ...ribPair(112),
      circle(16, 0, 17, 12),
      ...dotRow([-2, -14], [-2, 14], 2, 5),
    ],
  };
}

/** 一对肋骨的镂孔：沿躯干长轴某一处，左右各一根。 */
function ribPair(x) {
  return [
    [[x, -26], [x + 9, -20], [x + 12, -9], [x + 3, -13], [x - 4, -22]],
    [[x, 26], [x + 9, 20], [x + 12, 9], [x + 3, 13], [x - 4, 22]],
  ];
}

/**
 * 凡人的四肢。比悟空的细、素。
 * 末端那节带手/脚，不然肢体是根削尖的木棍。
 * @param {number} len
 * @param {'upper'|'fore'|'thigh'|'shin'} kind
 * @returns {Piece}
 */
export function folkLimb(len, kind) {
  const w = kind === 'upper' || kind === 'fore' ? 13 : 16;

  if (kind === 'fore') {
    // 小臂 + 收口的袖 + 手
    const c = len * 0.7;
    return {
      outline: [
        [0, -w], [c * 0.9, -w - 2], [c, -w - 5],
        [len - 5, -8], [len, -4], [len, 6], [len - 5, 9],
        [c, w + 4], [c * 0.9, w + 1], [0, w],
      ],
      holes: [],
      cuts: [
        [[c, -w - 3], [c, w + 2]], // 袖口
        [[len - 2, -3], [c + 5, -2]], // 手指缝
      ],
      bones: [longBone(c)],
    };
  }

  if (kind === 'shin') {
    // 小腿 + 朝正面（+y）的鞋。凡人穿布鞋，不是战靴
    return {
      outline: [
        [0, -w], [len * 0.88, -w + 3], [len, -8],
        [len + 6, -2], [len + 5, 10], [len * 0.9, 17],
        [len * 0.88, w], [0, w],
      ],
      holes: [],
      cuts: [
        [[len * 0.86, -w + 4], [len * 0.86, w - 1]], // 脚踝
        [[len + 3, 2], [len * 0.94, 12]], // 鞋帮
      ],
      bones: [longBone(len * 0.86)],
    };
  }

  // 大臂 / 大腿：一段带收束的管
  return {
    outline: [
      [0, -w],
      [len * 0.5, -w * 0.88],
      [len, -w * 0.66],
      [len, w * 0.66],
      [len * 0.5, w * 0.88],
      [0, w],
    ],
    holes: [],
    cuts: [[[len * 0.9, -w * 0.7], [len * 0.9, w * 0.7]]],
    bones: [longBone(len)],
  };
}

/** 长骨：中间一道细长孔，两头留出关节。 */
function longBone(len) {
  return [
    [len * 0.16, -4], [len * 0.5, -5], [len * 0.84, -4],
    [len * 0.84, 4], [len * 0.5, 5], [len * 0.16, 4],
  ];
}

